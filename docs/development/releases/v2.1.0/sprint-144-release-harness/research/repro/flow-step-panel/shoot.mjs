#!/usr/bin/env node
// Drives harness.html in a headless Chromium over raw CDP (Node 22's built-in WebSocket; no npm packages),
// measures the Flow editor's step panel and saves screenshots.
//
//   node shoot.mjs [--out <dir>] [--chrome <path>] [--no-shots]
//
// Writes theme-light.css first (Ritemark Light's colours as --vscode-* variables), then runs:
//   layout   the LLM step selected at several webview sizes: where the footer sits against the fields
//   loading  the model picker's state over time after a step is selected, as the host answers today
//   fixed    the same with the host answering with the right model type (replyFix=1)
//   late     flow:modelConfig sent after the step's panel has mounted (a slow host)
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../../../../../..');
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf('--' + name);
  return i >= 0 ? args[i + 1] : fallback;
};
const outDir = path.resolve(opt('out', path.resolve(here, '../../../qa')));
const shots = !args.includes('--no-shots');

// ---------------------------------------------------------------- theme
function readJsonc(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[}\]])/g, '$1');
  return JSON.parse(text);
}
function themeColors(file) {
  const theme = readJsonc(file);
  const base = theme.include ? themeColors(path.resolve(path.dirname(file), theme.include)) : {};
  return { ...base, ...(theme.colors || {}) };
}
function writeTheme() {
  const ext = path.join(root, 'extensions/ritemark');
  const colors = themeColors(path.join(ext, 'themes/ritemark-light.json'));
  const pkg = JSON.parse(fs.readFileSync(path.join(ext, 'package.json'), 'utf8'));
  for (const c of pkg.contributes.colors || []) {
    const light = c.defaults && c.defaults.light;
    if (!(c.id in colors) && typeof light === 'string' && light.startsWith('#')) colors[c.id] = light;
  }
  const lines = [
    '/* Generated by shoot.mjs from extensions/ritemark/themes/ritemark-light.json (with its includes)',
    '   and the ritemark.* colour defaults in extensions/ritemark/package.json. VS Code sets these on <html>. */',
    ':root {',
    "  --vscode-font-family: -apple-system, BlinkMacSystemFont, sans-serif;",
    '  --vscode-font-weight: normal;',
    '  --vscode-font-size: 13px;',
    "  --vscode-editor-font-family: Menlo, Monaco, 'Courier New', monospace;",
    '  --vscode-editor-font-size: 12px;',
    ...Object.entries(colors).sort().map(([k, v]) => `  --vscode-${k.replace(/\./g, '-')}: ${v};`),
    '}',
    '',
  ];
  fs.writeFileSync(path.join(here, 'theme-light.css'), lines.join('\n'));
}

// ---------------------------------------------------------------- browser
function findChrome() {
  const explicit = opt('chrome', process.env.CHROME);
  if (explicit) return explicit;
  const cache = path.join(os.homedir(), 'Library/Caches/ms-playwright');
  if (fs.existsSync(cache)) {
    const shells = fs.readdirSync(cache).filter((d) => d.startsWith('chromium_headless_shell-')).sort().reverse();
    for (const d of shells) {
      const bin = path.join(cache, d, 'chrome-headless-shell-mac-arm64/chrome-headless-shell');
      if (fs.existsSync(bin)) return bin;
    }
  }
  const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  if (fs.existsSync(chrome)) return chrome;
  throw new Error('no Chromium found: pass --chrome <path>');
}

async function launch() {
  const bin = findChrome();
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'p4-harness-'));
  const argv = [
    '--headless=new', '--remote-debugging-port=0', `--user-data-dir=${profile}`,
    '--no-first-run', '--no-default-browser-check', '--allow-file-access-from-files', '--window-size=800,900',
  ];
  const proc = spawn(bin, argv, { stdio: 'ignore' });
  const portFile = path.join(profile, 'DevToolsActivePort');
  for (let i = 0; i < 100 && !fs.existsSync(portFile); i++) await sleep(100);
  const [port, wsPath] = fs.readFileSync(portFile, 'utf8').trim().split('\n');
  const ws = new WebSocket(`ws://127.0.0.1:${port}${wsPath}`);
  await new Promise((resolve, reject) => { ws.onopen = resolve; ws.onerror = reject; });
  let id = 0;
  const pending = new Map();
  ws.onmessage = (event) => {
    const msg = JSON.parse(event.data);
    if (msg.id && pending.has(msg.id)) {
      const { resolve, reject } = pending.get(msg.id);
      pending.delete(msg.id);
      msg.error ? reject(new Error(JSON.stringify(msg.error))) : resolve(msg.result);
    }
  };
  const send = (method, params = {}, sessionId) => new Promise((resolve, reject) => {
    const msgId = ++id;
    pending.set(msgId, { resolve, reject });
    ws.send(JSON.stringify({ id: msgId, method, params, ...(sessionId ? { sessionId } : {}) }));
  });
  const { targetId } = await send('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await send('Target.attachToTarget', { targetId, flatten: true });
  const page = (method, params) => send(method, params, sessionId);
  await page('Page.enable');
  await page('Runtime.enable');
  const close = async () => {
    try { ws.close(); } catch {}
    const exited = new Promise((resolve) => proc.once('exit', resolve));
    proc.kill();
    await Promise.race([exited, sleep(3000)]);
    try { fs.rmSync(profile, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }); } catch {}
  };
  return { page, close, bin };
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function evaluate(page, expression) {
  const res = await page('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true });
  if (res.exceptionDetails) throw new Error(JSON.stringify(res.exceptionDetails));
  return res.result.value;
}

async function open(page, { width, height, query }) {
  await page('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: false });
  const url = pathToFileURL(path.join(here, 'harness.html')).href + (query ? '?' + query : '');
  await page('Page.navigate', { url });
  for (let i = 0; i < 100; i++) {
    await sleep(50);
    const ready = await evaluate(page, "!!document.querySelector('.react-flow__node')").catch(() => false);
    if (ready) return;
  }
  throw new Error('flow editor did not render');
}

// Time since the harness clicked the step, from its own log.
const SINCE_SELECT = `(() => { const s = (window.__harnessLog||[]).find(e => e.what === 'select' && e.detail.startsWith('click'));
  return s ? Math.round(performance.now() - window.__harnessT0 - s.t) : null; })()`;

async function waitForSelect(page) {
  for (let i = 0; i < 100; i++) {
    const t = await evaluate(page, SINCE_SELECT);
    if (t !== null) return;
    await sleep(20);
  }
  throw new Error('the harness never clicked the step');
}

const MEASURE = `(() => {
  const r = (el) => { if (!el) return null; const b = el.getBoundingClientRect(); return { top: Math.round(b.top), bottom: Math.round(b.bottom), height: Math.round(b.height), left: Math.round(b.left), width: Math.round(b.width) }; };
  const panel = document.querySelector('.rm-flow-props');
  const scroll = panel && panel.querySelector('.overflow-y-auto');
  const del = panel && [...panel.querySelectorAll('button')].find(b => /Delete node/.test(b.textContent));
  const footer = del && del.closest('.flex-none');
  const numbers = panel ? [...panel.querySelectorAll('input[type=number]')] : [];
  const combos = panel ? [...panel.querySelectorAll('button[role=combobox]')] : [];
  const modelLabel = panel && [...panel.querySelectorAll('label')].find(l => l.textContent.trim() === 'Model');
  const modelField = modelLabel && modelLabel.parentElement;
  const desc = modelField && modelField.querySelector('p');
  const model = combos[1];
  return {
    sinceSelect: ${SINCE_SELECT},
    viewport: { width: innerWidth, height: innerHeight },
    panel: r(panel), panelRoot: r(panel && panel.firstElementChild),
    scroll: scroll && { ...r(scroll), clientHeight: scroll.clientHeight, scrollHeight: scroll.scrollHeight, scrollTop: Math.round(scroll.scrollTop), overflowY: getComputedStyle(scroll).overflowY },
    footer: r(footer),
    temperature: r(numbers[0]), maxTokens: r(numbers[1]),
    temperatureVisibleInScroll: scroll && numbers[0] ? numbers[0].getBoundingClientRect().bottom <= scroll.getBoundingClientRect().bottom : null,
    model: model && { text: model.textContent.trim(), disabled: model.disabled || model.hasAttribute('data-disabled'), opacity: getComputedStyle(model).opacity },
    modelDescription: desc ? desc.textContent.trim() : null,
    log: (window.__harnessLog || []).map(e => e.t + 'ms ' + e.what + ' ' + e.detail),
  };
})()`;

async function measure(page) { return evaluate(page, MEASURE); }

async function shot(page, file, clip) {
  if (!shots) return;
  const params = { format: 'png', captureBeyondViewport: false };
  if (clip) params.clip = { ...clip, scale: clip.scale ?? 1 };
  const { data } = await page('Page.captureScreenshot', params);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, file), Buffer.from(data, 'base64'));
  console.log('  saved', path.relative(root, path.join(outDir, file)));
}

async function scrollPanelToEnd(page) {
  await evaluate(page, "(() => { const s = document.querySelector('.rm-flow-props .overflow-y-auto'); if (s) s.scrollTop = s.scrollHeight; })()");
  await sleep(100);
}

// ---------------------------------------------------------------- scenarios
writeTheme();
const { page, close, bin } = await launch();
const results = { chrome: bin, layout: [], loading: [], fixed: [], late: [] };
try {
  // 1. Layout: the desk's webview at 1440 x 900 is 784 x 824 with both columns
  //    (docs/development/frame-baseline/light-base.png: the desk's sheet spans x 256-1039, y 44-867).
  const sizes = [
    [784, 824, 'both columns at 1440 x 900'],
    [784, 800, 'nearby height'],
    [784, 760, 'nearby height'],
    [784, 700, 'nearby height'],
    [784, 640, 'nearby height'],
    [1032, 824, 'left column hidden'],
    [784, 1000, 'tall, for reference'],
  ];
  for (const [width, height, note] of sizes) {
    await open(page, { width, height, query: 'replyFix=1' });
    await waitForSelect(page);
    await sleep(800);
    const m = await measure(page);
    const entry = { size: `${width}x${height}`, note, ...m };
    if (width === 784 && height === 824) await shot(page, 'p4-footer-784x824.png');
    if (width === 784 && height === 800) {
      await shot(page, 'p4-footer-784x800-panel.png', { x: 536, y: height - 300, width: 248, height: 300, scale: 2 });
    }
    await scrollPanelToEnd(page);
    entry.afterScrollToEnd = await measure(page);
    delete entry.log; delete entry.afterScrollToEnd.log;
    results.layout.push(entry);
  }

  // 2. Loading: the host as it is today (answers with modelType 'flow:getModels').
  await open(page, { width: 784, height: 824, query: 'modelsDelay=150' });
  await waitForSelect(page);
  for (const at of [250, 1000, 3000, 4800, 5400]) {
    for (;;) { const t = await evaluate(page, SINCE_SELECT); if (t >= at) break; await sleep(10); }
    const m = await measure(page);
    results.loading.push({ at, sinceSelect: m.sinceSelect, model: m.model, modelDescription: m.modelDescription });
    if (at === 250) await shot(page, 'p4-model-loading-250ms.png', { x: 536, y: 52, width: 248, height: 300, scale: 2 });
    if (at === 5400) {
      await shot(page, 'p4-model-loading-5400ms.png', { x: 536, y: 52, width: 248, height: 300, scale: 2 });
      results.loadingLog = m.log;
    }
  }

  // 3. The same with the host answering with the right model type.
  await open(page, { width: 784, height: 824, query: 'modelsDelay=150&replyFix=1' });
  await waitForSelect(page);
  for (const at of [50, 250, 1000]) {
    for (;;) { const t = await evaluate(page, SINCE_SELECT); if (t >= at) break; await sleep(10); }
    const m = await measure(page);
    results.fixed.push({ at, sinceSelect: m.sinceSelect, model: m.model, modelDescription: m.modelDescription });
  }

  // 4. A slow host: flow:modelConfig arrives 1.5 s after the step's panel mounted (host answers as today).
  await open(page, { width: 784, height: 824, query: 'modelConfigDelay=1500&selectAt=100&modelsDelay=150' });
  await waitForSelect(page);
  for (const at of [250, 2500, 6000]) {
    for (;;) { const t = await evaluate(page, SINCE_SELECT); if (t >= at) break; await sleep(10); }
    const m = await measure(page);
    results.late.push({ at, sinceSelect: m.sinceSelect, model: m.model, modelDescription: m.modelDescription });
    if (at === 6000) results.lateLog = m.log;
  }
} finally {
  await close();
}
console.log(JSON.stringify(results, null, 2));
