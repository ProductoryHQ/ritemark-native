import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {driver,findWebview,waitFor,session,writeEvidence,targets,connectCdp,evidence} from './live-tools.mjs';
const xlsx=createRequire(import.meta.url)('../../../../../extensions/ritemark/node_modules/xlsx');
const file=path.join(session.workspace,'book.xlsx');
const cell=()=>xlsx.readFile(file).Sheets.Sheet1.B2.v;
const replace=v=>{const b=xlsx.readFile(file);b.Sheets.Sheet1.B2={t:'s',v};xlsx.writeFile(b,file);};
const report={method:'Repeat normal cell-edit / external replacement / Save after explicitly refreshing a clean workbook. Record modal dialogs separately from nonmodal notifications. Observe disk writes and the ordinary Save result.',steps:[]};
const record=(stage,data)=>{report.steps.push({stage,at:Date.now(),...data});writeEvidence('live-excel-repeat-probe.json',report);};
let v,c;
try{
  await driver('/open',{file:'book.xlsx'});
  v=await findWebview("!!document.querySelector('td[title=\"HUMAN EDIT\"]')");
  assert.ok((await driver()).tabs.some(g=>g.tabs.some(t=>t.label==='book.xlsx'&&!t.dirty)));
  replace('REPEAT BASELINE');
  await new Promise(r=>setTimeout(r,1100));
  await v.evaluate("[...document.querySelectorAll('button')].find(e=>e.textContent.trim()==='Refresh').click()");
  await waitFor(()=>v.evaluate("!!document.querySelector('td[title=\"REPEAT BASELINE\"]')"));
  c=await connectCdp((await targets()).find(t=>t.type==='page'&&t.url.includes('workbench')).webSocketDebuggerUrl);
  const dialogs=async()=>(await c.send('Runtime.evaluate',{expression:"({modal:[...document.querySelectorAll('.monaco-dialog-box,[aria-modal=true]')].filter(e=>e.getBoundingClientRect().width>0).map(e=>e.innerText),notifications:[...document.querySelectorAll('.notification-list-item')].filter(e=>e.getBoundingClientRect().width>0).map(e=>e.innerText)})",returnByValue:true})).result.value;
  record('refreshed-clean',{host:await driver(),disk:cell(),dialogs:await dialogs()});
  await v.evaluate("document.querySelector('td[title=\"REPEAT BASELINE\"]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,detail:2}))");
  await waitFor(()=>v.evaluate("!!document.querySelector('td textarea')"));
  await v.evaluate("(()=>{const t=document.querySelector('td textarea');t.focus();t.select();})()");
  await v.cdp.send('Input.insertText',{text:'REPEAT HUMAN'});
  for(const type of ['keyDown','keyUp'])await v.cdp.send('Input.dispatchKeyEvent',{type,key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
  await waitFor(async()=>(await driver()).tabs.some(g=>g.tabs.some(t=>t.label==='book.xlsx'&&t.dirty)));
  assert.equal(cell(),'REPEAT BASELINE');
  replace('REPEAT EXTERNAL');
  await new Promise(r=>setTimeout(r,1100));
  record('external-replacement',{host:await driver(),disk:cell(),visible:await v.evaluate('document.body.innerText'),dialogs:await dialogs()});
  const save=await driver('/command',{command:'workbench.action.files.save'});
  await waitFor(()=>cell()==='REPEAT HUMAN');
  const after=await dialogs();
  record('saved',{host:save,disk:cell(),visible:await v.evaluate('document.body.innerText'),dialogs:after});
  assert.ok(save.tabs.some(g=>g.tabs.some(t=>t.label==='book.xlsx'&&!t.dirty)));
  report.externalChangeOverwritten=true;report.saveReturnedWithoutInterveningUIAction=true;report.modalAfterSave=after.modal;report.completed=true;
  const shot=await c.send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(evidence,'live-excel-repeat.png'),Buffer.from(shot.data,'base64'));
  writeEvidence('live-excel-repeat-probe.json',report);console.log(JSON.stringify({completed:true,externalChangeOverwritten:true,modalAfterSave:after.modal}));
}catch(e){record('error',{error:String(e.stack??e)});throw e;}finally{v?.close();c?.close();}
