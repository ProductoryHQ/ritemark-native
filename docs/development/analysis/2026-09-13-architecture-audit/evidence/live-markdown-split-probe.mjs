import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {driver,findWebview,waitFor,session,writeEvidence,targets,connectCdp,evidence} from './live-tools.mjs';
const name='second.md',file=path.join(session.workspace,name),marker=' PEER EDIT '+Date.now();
const report={method:'Actual two split custom-editor views of the same synthetic Markdown document in one extension host. View-two input, peer delivery, external conflict to both views, Keep my version, and one-view disposal. This is not a two-window or cross-process test.',steps:[]};
const record=(stage,data)=>{report.steps.push({stage,at:Date.now(),...data});writeEvidence('live-markdown-split-probe.json',report);};
let a,b,c;
try{
 await driver('/open',{file:name});
 a=await findWebview("document.querySelector('.ProseMirror')?.innerText.includes('HUMAN UNSAVED')");
 await a.evaluate("window.__auditSplitFirst=true");
 await driver('/command',{command:'workbench.action.splitEditorRight'});
 b=await findWebview("!window.__auditSplitFirst&&document.querySelector('.ProseMirror')?.innerText.includes('HUMAN UNSAVED')");
 assert.notEqual(a.targetId,b.targetId);
 const text=v=>v.evaluate("document.querySelector('.ProseMirror').innerText");
 for(const v of[a,b])await v.evaluate("window.__auditSplitMessages=[];window.addEventListener('message',e=>{if(e.data?.type?.startsWith('document:'))window.__auditSplitMessages.push(e.data)})");
 record('split-open',{host:await driver(),targets:[a.targetId,b.targetId],views:[await text(a),await text(b)]});
 await b.evaluate("(()=>{const e=document.querySelector('.ProseMirror');e.focus();const r=document.createRange();r.selectNodeContents(e);r.collapse(false);const s=getSelection();s.removeAllRanges();s.addRange(r);})()");
 const start=Date.now();await b.cdp.send('Input.insertText',{text:marker});
 await waitFor(async()=>(await text(a)).includes(marker)&&(await text(b)).includes(marker)&&(await driver()).documents.find(d=>d.file===name)?.text.includes(marker));
 const local=(await driver()).documents.find(d=>d.file===name).text;
 record('peer-edit',{observedWithinMs:Date.now()-start,host:await driver(),views:[await text(a),await text(b)]});
 const external='# EXTERNAL SPLIT '+Date.now()+'\n\nSeparate actor version.\n';
 fs.writeFileSync(file,external);
 const hash=crypto.createHash('sha256').update(external).digest('hex');
 for(const v of[a,b])await waitFor(()=>v.evaluate("window.__auditSplitMessages.some(e=>e.type==='document:conflict'&&e.diskHash==="+JSON.stringify(hash)+")"));
 assert.equal((await driver()).documents.find(d=>d.file===name).text,local);
 assert.equal(fs.readFileSync(file,'utf8'),external);
 record('two-view-conflict',{host:await driver(),disk:external,views:[await text(a),await text(b)]});
 await a.evaluate("[...document.querySelectorAll('button')].find(e=>e.textContent.trim()==='Review changes').click()");
 await waitFor(()=>a.evaluate("[...document.querySelectorAll('button')].some(e=>e.textContent.trim()==='Keep my version')"));
 await a.evaluate("[...document.querySelectorAll('button')].find(e=>e.textContent.trim()==='Keep my version').click()");
 await waitFor(async()=>{const d=(await driver()).documents.find(d=>d.file===name);return d?.text===local&&!d.dirty&&fs.readFileSync(file,'utf8')===local;});
 record('keep-local-clean',{host:await driver(),disk:fs.readFileSync(file,'utf8'),views:[await text(a),await text(b)],messages:[await a.evaluate('window.__auditSplitMessages'),await b.evaluate('window.__auditSplitMessages')]});
 c=await connectCdp((await targets()).find(t=>t.type==='page'&&t.url.includes('workbench')).webSocketDebuggerUrl);
 const shot=await c.send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(evidence,'live-markdown-split.png'),Buffer.from(shot.data,'base64'));
 const before=await driver();
 await driver('/command',{command:'workbench.action.closeActiveEditor'});
 const remaining=await driver();
 assert.equal(remaining.documents.find(d=>d.file===name)?.text,local);
 record('one-view-close',{before,after:remaining,targets:(await targets()).map(t=>({id:t.id,type:t.type})),disk:fs.readFileSync(file,'utf8')});
 report.completed=true;writeEvidence('live-markdown-split-probe.json',report);console.log(JSON.stringify({completed:true,stages:report.steps.map(s=>s.stage)}));
}catch(e){record('error',{error:String(e.stack??e)});throw e;}finally{a?.close();b?.close();c?.close();}
